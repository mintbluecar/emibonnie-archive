// @ts-check
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const GENERATED_HEADER = '// GENERATED by scripts/build.js from site/ and src/kinds/*/. Do not edit.\n';

/**
 * Strict security headers, from the design spec's "Trust, safety and
 * privacy" → Headers bullets (`Referrer-Policy: no-referrer`, not
 * `strict-origin` -- a later ruling superseded the spec's own wording).
 */
export const SECURITY_HEADERS = [
  {
    key: 'Content-Security-Policy',
    value:
      "default-src 'self'; script-src 'self'; style-src 'self'; font-src 'self'; " +
      "img-src 'self' https://pbs.twimg.com; media-src 'self' https://video.twimg.com; " +
      "frame-ancestors 'none'; base-uri 'self'; form-action 'self'",
  },
  { key: 'Referrer-Policy', value: 'no-referrer' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains; preload' },
];

/** `/build/*` (hashed JS/CSS/fonts from `scripts/buildBundle.js`) is safe to cache forever: a content change is always a new filename. */
const BUILD_CACHE_HEADERS = [{ source: '/build/(.*)', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] }];

/**
 * `src/site/generated.js`: a statically-importable module so Vercel bundles
 * it, with no runtime `fs` reads in functions.
 * @param {import('../src/site/schema.js').Site} site
 * @param {Record<string, string>} copy
 * @param {{ logo: string|null }} [assets] public paths of the site's copied assets (the logo, for link previews)
 * @returns {string}
 */
export function buildGeneratedSiteModule(site, copy, assets = { logo: null }) {
  return (
    `${GENERATED_HEADER}// @ts-check\n` +
    `export const site = ${JSON.stringify(site, null, 2)};\n\n` +
    `export const copy = ${JSON.stringify(copy, null, 2)};\n\n` +
    `/** @type {{ logo: string|null }} */\nexport const assets = ${JSON.stringify(assets)};\n`
  );
}

/**
 * `public/site/site.js`: the public subset of `site` (without
 * `ownerXUserId`) plus `copy` and the site's logo path (if any, copied by
 * `copySiteAssets()` into this same `public/site/` directory), so
 * `public/js/core/site.js`'s `t()` and `site` have everything a page or
 * component needs from this one module.
 * @param {import('../src/site/schema.js').Site} site
 * @param {Record<string, string>} [copy]
 * @param {{ logo: string|null }} [assets]
 * @returns {string}
 */
export function buildPublicSiteModule(site, copy = {}, assets = { logo: null }) {
  /** @type {any} */
  const publicSite = { ...site, logo: assets.logo };
  delete publicSite.ownerXUserId;
  return (
    `${GENERATED_HEADER}export const site = ${JSON.stringify(publicSite, null, 2)};\n\n` +
    `export const copy = ${JSON.stringify(copy, null, 2)};\n`
  );
}

/**
 * Sorted kind folder names directly under `kindsDir`.
 * @param {string} kindsDir
 * @returns {string[]}
 */
export function listKindFolders(kindsDir) {
  if (!existsSync(kindsDir)) return [];
  return readdirSync(kindsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

/**
 * `src/kinds/_registry.js`: a static default import of every kind
 * folder's `index.js` (its `defineKind(...)` result), sorted, so each
 * entry is the Kind itself. An empty `kindNames` list is valid.
 * @param {string[]} kindNames
 * @returns {string}
 */
export function buildKindsRegistryModule(kindNames) {
  const imports = kindNames.map((name, i) => `import kind${i} from './${name}/index.js';`);
  const entries = kindNames.map((name, i) => `  ${JSON.stringify(name)}: kind${i},`);
  return (
    `${GENERATED_HEADER}// @ts-check\n${imports.length > 0 ? `${imports.join('\n')}\n\n` : ''}` +
    `/** @type {Record<string, Readonly<import('./defineKind.js').Kind>>} */\n` +
    `export const kindsRegistry = {\n${entries.join('\n')}\n};\n`
  );
}

/**
 * `public/js/kinds/_registry.js` (Plan 1b Task 2): a static import of
 * each `public/js/kinds/<kind>/{section,detail}.js` pair, sorted, plus
 * `renderSections()`, the one generic helper every hub page uses to turn
 * API `Section`s into markup. A section whose `kind` this build has no
 * front-end for (e.g. a kind scaffolded after this bundle was built) is
 * silently skipped, never thrown on -- a rolling deploy, or a kind with
 * server support but no UI yet, must not break every hub page. Each
 * entry also carries its `urlPrefix` (from the server-side kinds
 * registry, read by `scripts/build.js` -- `null` if a kind somehow has
 * none), so the item page (Plan 1b Task 4) can map a URL's prefix back
 * to a kind name without any page ever naming one itself.
 * @param {string[]} kindNames
 * @param {Record<string, string>} [urlPrefixes]
 * @returns {string}
 */
export function buildFrontendKindsRegistryModule(kindNames, urlPrefixes = {}) {
  const imports = kindNames.flatMap((name, i) => [
    `import * as section${i} from './${name}/section.js';`,
    `import * as detail${i} from './${name}/detail.js';`,
  ]);
  const entries = kindNames.map(
    (name, i) => `  ${JSON.stringify(name)}: { section: section${i}, detail: detail${i}, urlPrefix: ${JSON.stringify(urlPrefixes[name] ?? null)} },`,
  );
  return (
    `${GENERATED_HEADER}// @ts-check\n${imports.length > 0 ? `${imports.join('\n')}\n\n` : ''}` +
    `/** @type {Record<string, { section: { render: Function, bind?: Function }, detail: { render: Function, bind?: Function }, urlPrefix: string|null }>} */\n` +
    `export const KIND_UI = {\n${entries.join('\n')}\n};\n\n` +
    '/**\n' +
    ' * Renders every section whose kind this build has UI for, in registry\n' +
    ' * order; a section for an unknown kind is left out, not thrown on.\n' +
    " * @param {import('../../../src/http/contracts.js').Section[]} sections\n" +
    ' * @param {any} ctx\n' +
    " * @returns {import('../core/html.js').SafeHtml[]}\n" +
    ' */\n' +
    'export function renderSections(sections, ctx) {\n' +
    '  return sections.filter((section) => KIND_UI[section.kind]).map((section) => KIND_UI[section.kind].section.render(section, ctx));\n' +
    '}\n'
  );
}

/**
 * Writes `src/kinds/_registry.js` and `public/js/kinds/_registry.js` under
 * `repoRoot`, the one place either file is generated (Plan 1b Task 7,
 * carried item B): several test files used to `writeFileSync` these same
 * paths themselves, which raced across `node --test`'s parallel worker
 * processes. `npm test`'s `pretest` script (`scripts/genRegistries.js`)
 * calls this once before any test file runs; `scripts/build.js` calls it
 * too, for the production build.
 * @param {string} repoRoot
 * @returns {Promise<void>}
 */
export async function writeKindsRegistries(repoRoot) {
  const kindsDir = path.join(repoRoot, 'src/kinds');
  mkdirSync(kindsDir, { recursive: true });
  writeFileSync(path.join(kindsDir, '_registry.js'), buildKindsRegistryModule(listKindFolders(kindsDir)));

  const { kindsRegistry } = await import(pathToFileURL(path.join(kindsDir, '_registry.js')).href);
  const urlPrefixes = Object.fromEntries(Object.entries(kindsRegistry).map(([name, kind]) => [name, /** @type {any} */ (kind).urlPrefix]));

  const feKindsDir = path.join(repoRoot, 'public/js/kinds');
  mkdirSync(feKindsDir, { recursive: true });
  writeFileSync(path.join(feKindsDir, '_registry.js'), buildFrontendKindsRegistryModule(listKindFolders(feKindsDir), urlPrefixes));
}

/**
 * The one function (`api/index.js`), bundled with the built pages its
 * link-preview meta routes read. The key is a glob (`api/*.js`) that
 * matches it.
 */
export const FUNCTIONS = { 'api/*.js': { includeFiles: 'public/{item,event}.html' } };

/**
 * `vercel.json`'s content: region, security headers (plus an immutable
 * long-lived cache header on `/build/*`, Plan 1b's hashed esbuild
 * output), build command, the function's bundled pages, and the
 * rewrites (the route table's function rewrites, all to `/api`, then the
 * `src/pages.js` static-file rewrites from Plan 1b).
 * @param {import('../src/site/schema.js').Site} site
 * @param {{ source: string, destination: string }[]} rewrites
 * @returns {object}
 */
export function buildVercelConfig(site, rewrites = []) {
  /** @type {any} */
  const config = {
    regions: [site.region],
    buildCommand: 'npm run build',
    functions: FUNCTIONS,
    headers: [{ source: '/(.*)', headers: SECURITY_HEADERS }, ...BUILD_CACHE_HEADERS],
  };
  if (rewrites.length > 0) config.rewrites = rewrites;
  return config;
}
