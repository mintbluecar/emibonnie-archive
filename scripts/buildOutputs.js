// @ts-check
import { existsSync, readdirSync } from 'node:fs';

const GENERATED_HEADER = '// GENERATED by scripts/build.js from site/ and src/kinds/*/. Do not edit.\n';

/**
 * Strict security headers, from the design spec's "Trust, safety and
 * privacy" → Headers bullets (`Referrer-Policy: no-referrer`, not
 * `strict-origin` -- a later ruling superseded the spec's own wording).
 */
export const SECURITY_HEADERS = [
  {
    key: 'Content-Security-Policy',
    value:
      "default-src 'self'; script-src 'self'; style-src 'self'; " +
      "img-src 'self' https://pbs.twimg.com; media-src 'self' https://video.twimg.com; " +
      "frame-ancestors 'none'; base-uri 'self'; form-action 'self'",
  },
  { key: 'Referrer-Policy', value: 'no-referrer' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains; preload' },
];

/**
 * `src/site/generated.js`: a statically-importable module so Vercel bundles
 * it, with no runtime `fs` reads in functions.
 * @param {import('../src/site/schema.js').Site} site
 * @param {Record<string, string>} copy
 * @returns {string}
 */
export function buildGeneratedSiteModule(site, copy) {
  return (
    `${GENERATED_HEADER}// @ts-check\n` +
    `export const site = ${JSON.stringify(site, null, 2)};\n\n` +
    `export const copy = ${JSON.stringify(copy, null, 2)};\n`
  );
}

/**
 * `public/site/site.js`: the public subset of `site`, without
 * `ownerXUserId`.
 * @param {import('../src/site/schema.js').Site} site
 * @returns {string}
 */
export function buildPublicSiteModule(site) {
  /** @type {any} */
  const publicSite = { ...site };
  delete publicSite.ownerXUserId;
  return `${GENERATED_HEADER}export const site = ${JSON.stringify(publicSite, null, 2)};\n`;
}

/**
 * Sorted kind folder names directly under `kindsDir`.
 * @param {string} kindsDir
 * @returns {string[]}
 */
export function listKindFolders(kindsDir) {
  if (!existsSync(kindsDir)) return [];
  return readdirSync(kindsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

/**
 * `src/kinds/_registry.js`: static imports of every kind folder's
 * `index.js`, sorted. An empty `kindNames` list is valid (no kinds yet).
 * @param {string[]} kindNames
 * @returns {string}
 */
export function buildKindsRegistryModule(kindNames) {
  const imports = kindNames.map((name, i) => `import * as kind${i} from './${name}/index.js';`);
  const entries = kindNames.map((name, i) => `  ${JSON.stringify(name)}: kind${i},`);
  return (
    `${GENERATED_HEADER}// @ts-check\n${imports.length > 0 ? `${imports.join('\n')}\n\n` : ''}` +
    `/** @type {Record<string, unknown>} */\n` +
    `export const kindsRegistry = {\n${entries.join('\n')}\n};\n`
  );
}

/**
 * `vercel.json`'s content: region, security headers, build command, and
 * any page rewrites (Plan 1b; empty for now).
 * @param {import('../src/site/schema.js').Site} site
 * @param {{ source: string, destination: string }[]} pageRewrites
 * @returns {object}
 */
export function buildVercelConfig(site, pageRewrites = []) {
  /** @type {any} */
  const config = {
    regions: [site.region],
    buildCommand: 'npm run build',
    headers: [{ source: '/(.*)', headers: SECURITY_HEADERS }],
  };
  if (pageRewrites.length > 0) config.rewrites = pageRewrites;
  return config;
}
